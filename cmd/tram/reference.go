import (
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	"strings"

	"github.com/spf13/cobra"
)

// referencePath is where tram reference writes the command reference, from
// the root of the repository.
const referencePath = "docs/cli-reference.md"

func newReferenceCmd() *cobra.Command {
	return &cobra.Command{
		Use:    "reference [file]",
		Short:  "Write the command reference as Markdown",
		Hidden: true,
		Args:   cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if len(args) == 0 {
				return writeReference(cmd.OutOrStdout())
			}
			f, err := os.Create(args[0])
			if err != nil {
				return err
			}
			return errors.Join(writeReference(f), f.Close())
		},
	}
}

// writeReference writes the reference of every command of tram, from its
// help: the usage, the description, the examples and the flags. It documents
// the binary as tram, not as the kubectl plugin.
func writeReference(out io.Writer) error {
	root := newRootCmd(slog.New(slog.DiscardHandler), &slog.LevelVar{})
	// Cobra adds the completion command only when it runs.
	root.InitDefaultCompletionCmd()
	var b strings.Builder
	b.WriteString(`# Command Reference

<!-- Generated by tram reference from the help of the commands; run
     task generate after changing a command. Do not edit. -->

Every command of the ` + "`tram`" + ` binary with its flags, as ` + "`--help`" + ` shows them. As the
kubectl plugin ` + "`kubectl tram`" + `, the binary has the commands that work with streams
and stream files, and Kubernetes is their default target; see
[The tram CLI](../README.md#the-tram-cli).
`)
	writeCommand(&b, root)
	_, err := io.WriteString(out, b.String())
	return err
}

func writeCommand(b *strings.Builder, cmd *cobra.Command) {
	if !documented(cmd) {
		return
	}
	cmd.InitDefaultHelpFlag()
	fmt.Fprintf(b, "\n## %s\n\n%s\n", cmd.CommandPath(), cmd.Short)
	if long := strings.TrimSpace(cmd.Long); long != "" && long != cmd.Short {
		fmt.Fprintf(b, "\n%s\n", long)
	}
	if cmd.Runnable() {
		fmt.Fprintf(b, "\n```\n%s\n```\n", cmd.UseLine())
	}
	if cmd.Example != "" {
		fmt.Fprintf(b, "\n**Examples**\n\n```\n%s\n```\n", strings.TrimRight(cmd.Example, "\n"))
	}
	writeFlags(b, "Flags", cmd.NonInheritedFlags().FlagUsagesWrapped(0))
	writeFlags(b, "Inherited flags", cmd.InheritedFlags().FlagUsagesWrapped(0))

	var subs []string
	for _, sub := range cmd.Commands() {
		if documented(sub) {
			subs = append(subs, fmt.Sprintf("[%s](#%s)", sub.CommandPath(), anchor(sub.CommandPath())))
		}
	}
	if len(subs) > 0 {
		fmt.Fprintf(b, "\n**Commands:** %s\n", strings.Join(subs, ", "))
	}
	for _, sub := range cmd.Commands() {
		writeCommand(b, sub)
	}
}

func writeFlags(b *strings.Builder, title, usages string) {
	if usages = strings.TrimRight(usages, "\n"); usages != "" {
		fmt.Fprintf(b, "\n**%s**\n\n```\n%s\n```\n", title, usages)
	}
}

// documented reports whether the reference lists cmd: not the hidden ones,
// help, and the completion scripts of each shell.
func documented(cmd *cobra.Command) bool {
	if cmd.Hidden || cmd.Name() == "help" {
		return false
	}
	return cmd.Parent() == nil || cmd.Parent().Name() != "completion"
}

// anchor is the anchor of the heading of a command path.
func anchor(path string) string {
	return strings.ReplaceAll(path, " ", "-")
}
